"""Fixtures for disposable PostgreSQL 16 role tests.

These fixtures create and destroy a dedicated PostgreSQL 16 container and
volume for role-bootstrap validation. They read only NETOPS_TEST_DATABASE_URL
and never fall back to NETOPS_DATABASE_URL.

Docker is started and stopped within the session scope. Credentials are
generated ephemerally and are never logged or printed.
"""

from __future__ import annotations

import asyncio
import os
import secrets
import subprocess
import time
from typing import Generator

import asyncpg
import pytest

from ..postgres_test_support import (
    TEST_DATABASE_URL_ENV,
    DisposablePostgresTarget,
    TestDatabaseSafetyError,
    assert_disposable_database_name,
    load_disposable_test_target,
    parse_disposable_test_url,
)

DOCKER_IMAGE = "postgres:16"
CONTAINER_PREFIX = "netops-8-2-3-pg16-"
VOLUME_PREFIX = "netops-8-2-3-pg16-data-"
DB_PREFIX = "netops_test_"
DB_USER_PREFIX = "netops_test_user_"


def _run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(
            f"Command {' '.join(cmd)} failed ({result.returncode}): {result.stderr.strip()}"
        )
    return result.stdout.strip()


def _generate_suffix() -> str:
    return secrets.token_hex(8)


def _generate_password() -> str:
    return secrets.token_hex(24)


@pytest.fixture(scope="session")
def disposable_postgres_cluster() -> Generator[DisposablePostgresTarget, None, None]:
    """Create a dedicated disposable PostgreSQL 16 container for the session.

    Yields a validated DisposablePostgresTarget. The container and volume are
    removed when the session ends, even on failure.
    """
    if os.environ.get("NETOPS_DATABASE_URL"):
        raise TestDatabaseSafetyError(
            "NETOPS_DATABASE_URL is set; refusing to run role tests against "
            "the application database. Set only NETOPS_TEST_DATABASE_URL."
        )

    raw_url = os.environ.get(TEST_DATABASE_URL_ENV)
    target: DisposablePostgresTarget | None = None
    container: str | None = None
    volume: str | None = None

    if raw_url:
        # Caller provided a disposable target; validate and reuse, but do not
        # create or destroy container resources we did not create.
        target = parse_disposable_test_url(raw_url)
        assert_disposable_database_name(target.database)

        # Set ephemeral passwords on netops_migrator and netops_runtime so
        # tests can connect as those roles. These are test-only credentials
        # and are never logged or printed.
        migrator_password = secrets.token_hex(16)
        runtime_password = secrets.token_hex(16)

        admin_kwargs = target.asyncpg_connect_kwargs()
        async def _configure_roles() -> None:
            admin_conn = await asyncpg.connect(**admin_kwargs)
            try:
                # Passwords are hex strings generated by secrets.token_hex(16),
                # so they contain only [0-9a-f] and are safe to interpolate.
                await admin_conn.execute(
                    f"ALTER ROLE netops_migrator WITH PASSWORD '{migrator_password}'"
                )
                await admin_conn.execute(
                    f"ALTER ROLE netops_runtime WITH PASSWORD '{runtime_password}'"
                )
            finally:
                await admin_conn.close()

        asyncio.run(_configure_roles())

        # Attach test-only credentials to the target object for use by tests.
        object.__setattr__(target, "migrator_password", migrator_password)
        object.__setattr__(target, "runtime_password", runtime_password)

        yield target
        return

    suffix = _generate_suffix()
    container = f"{CONTAINER_PREFIX}{suffix}"
    volume = f"{VOLUME_PREFIX}{suffix}"
    database = f"{DB_PREFIX}{suffix}"
    db_user = f"{DB_USER_PREFIX}{suffix}"
    password = _generate_password()

    if not _docker_names_unused(container, volume):
        raise TestDatabaseSafetyError(
            f"Docker container {container} or volume {volume} already exists"
        )

    def _setup_and_yield() -> DisposablePostgresTarget:
        """Async body executed via asyncio.run()."""

        _run(
            [
                "docker",
                "run",
                "-d",
                "--name",
                container,
                "--env",
                f"POSTGRES_PASSWORD={password}",
                "--env",
                f"POSTGRES_USER={db_user}",
                "--env",
                f"POSTGRES_DB={database}",
                "--publish",
                "127.0.0.1::5432",
                "--volume",
                f"{volume}:/var/lib/postgresql/data",
                DOCKER_IMAGE,
            ]
        )

        # Parse assigned loopback port.
        mapping = _run(["docker", "port", container, "5432/tcp"]).splitlines()[0]
        host_port = mapping.rsplit(":", 1)[-1]
        host = mapping.split(":", 1)[0]

        # Wait for readiness.
        ready = False
        for _ in range(60):
            result = subprocess.run(
                [
                    "docker",
                    "exec",
                    container,
                    "pg_isready",
                    "-U",
                    db_user,
                    "-d",
                    database,
                ],
                capture_output=True,
                text=True,
            )
            if result.returncode == 0:
                ready = True
                break
            time.sleep(1)

        if not ready:
            raise TestDatabaseSafetyError(
                f"PostgreSQL container {container} did not become ready"
            )

        async def _configure_roles() -> DisposablePostgresTarget:
            url = (
                f"postgresql+asyncpg://{db_user}:{password}@{host}:{host_port}/{database}"
            )
            t = parse_disposable_test_url(url)
            assert_disposable_database_name(t.database)

            # Set ephemeral passwords on netops_migrator and netops_runtime so
            # tests can connect as those roles. These are test-only credentials
            # and are never logged or printed.
            migrator_password = secrets.token_hex(16)
            runtime_password = secrets.token_hex(16)

            admin_kwargs = t.asyncpg_connect_kwargs()
            admin_conn = await asyncpg.connect(**admin_kwargs)
            try:
                # Passwords are hex strings generated by secrets.token_hex(16),
                # so they contain only [0-9a-f] and are safe to interpolate.
                await admin_conn.execute(
                    f"ALTER ROLE netops_migrator WITH PASSWORD '{migrator_password}'"
                )
                await admin_conn.execute(
                    f"ALTER ROLE netops_runtime WITH PASSWORD '{runtime_password}'"
                )
            finally:
                await admin_conn.close()

            # Attach test-only credentials to the target object for use by tests.
            object.__setattr__(t, "migrator_password", migrator_password)
            object.__setattr__(t, "runtime_password", runtime_password)
            return t

        return asyncio.run(_configure_roles())

    target = _setup_and_yield()
    try:
        yield target
    finally:
        if container:
            _run(["docker", "rm", "-f", container])
        if volume:
            _run(["docker", "volume", "rm", volume])

        # Verify cleanup.
        remaining_containers = _run(
            ["docker", "ps", "-a", "--format", "{{.Names}}"]
        ).splitlines()
        remaining_volumes = _run(
            ["docker", "volume", "ls", "--format", "{{.Name}}"]
        ).splitlines()
        if container in remaining_containers:
            raise RuntimeError(f"Container {container} still present after cleanup")
        if volume in remaining_volumes:
            raise RuntimeError(f"Volume {volume} still present after cleanup")
